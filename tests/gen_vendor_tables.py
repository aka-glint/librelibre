#!/usr/bin/env python3
"""Generate vendor_tables.h (no duplicate arrays): the recovered chain shares the
SINGLE physical t1/t2 rodata that factory.c already carries, plus a tiny slope
table. This avoids shipping the two 8184-byte tables twice.

Role mapping (see VENDOR-CHAIN-PORT.md): the vendor rodata at 0xa7850 (loaded
into config+0x10, the recovery docs' "t1") is the 0.1073... family, which is
DiaBLE's `t2`; the vendor 0xa9850 (config+0x18, "t2") is the 1.5/2.0/... family,
DiaBLE's `t1`. factory.c's arrays are named by the DiaBLE source, so the shared
accessors below map vendor roles onto them explicitly.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
out_h = '''/* GENERATED by tests/gen_vendor_tables.py -- do not edit by hand. */
#pragma once

/* Recupeured f64 calibration tables. There is exactly ONE physical copy of the
 * big t1/t2 tables: the arrays in factory.c (name-mapped to the vendor roles).
 * vendor_tables.c only adds the 8-entry slope table. */
extern const double LC_VENDOR_SLOPE_TABLE[8];

/* vendor config+0x10 ("t1", 0.1073... family) == factory.c's DiaBLE `t2`
 * vendor config+0x18 ("t2", 1.5 family)       == factory.c's DiaBLE `t1`
 * Indexing is [i2-1] (0x579e4 load [t+idx*8-8]). */
const double* lc_vendor_table_t1(void);   /* == factory t2 array */
const double* lc_vendor_table_t2(void);   /* == factory t1 array */
'''
(ROOT / 'vendor_tables.h').write_text(out_h)
print('wrote vendor_tables.h (shared-table accessors)')
